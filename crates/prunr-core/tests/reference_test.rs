// Pixel-accuracy reference test
// ============================================================

/// Prunr output must match rembg Python output at 95% pixel accuracy.
///
/// This test runs process_image() on three test images using u2net and compares the
/// resulting alpha channel against masks generated by scripts/generate_references.py.
///
/// PREREQUISITE: Run `python scripts/generate_references.py` before running this test.
/// See tests/test_images/README.md for image download instructions.
#[test]
fn test_rembg_reference() {
    if skip_if_no_ort("test_rembg_reference") { return; }
    if skip_if_model_missing("test_rembg_reference", prunr_models::ModelId::U2net) { return; }
    let engine = OrtEngine::new(ModelKind::U2net, 1)
        .expect("Failed to create OrtEngine — U2Net reported available but session creation failed");

    let test_cases = ["car-1", "car-2", "car-3"];
    let tolerance: u8 = 5;   // |our_alpha - ref_alpha| <= 5 counts as match
    let required_pct: f64 = 95.0;

    for stem in &test_cases {
        let image_path = test_images_dir().join(format!("{stem}.jpg"));
        if !image_path.exists() {
            eprintln!("Skipping reference test for {stem}: image not found at {}", image_path.display());
            continue;
        }

        let img_bytes = std::fs::read(&image_path)
            .expect("Failed to read test image");

        let result = process_image(&img_bytes, &engine, &prunr_core::Progress::none())
            .unwrap_or_else(|e| panic!("process_image failed for {stem}: {e}"));

        let our_rgba = result.rgba_image;

        let Some(ref_mask) = load_reference_mask(stem) else {
            continue;
        };

        // Reference mask is at full-size (rembg returns full-size output matching the input).
        // If reference mask dimensions differ from our output, resize reference mask to match
        // (using nearest neighbor for pixel-accurate comparison).
        let ref_mask = if ref_mask.width() != our_rgba.width() || ref_mask.height() != our_rgba.height() {
            image::imageops::resize(
                &ref_mask,
                our_rgba.width(),
                our_rgba.height(),
                image::imageops::FilterType::Nearest,
            )
        } else {
            ref_mask
        };

        let pct = pixel_match_percent(&our_rgba, &ref_mask, tolerance);

        assert!(
            pct >= required_pct,
            "rembg reference failed for {stem}: {pct:.1}% match (required {required_pct}%)\n\
             Check preprocessing pipeline matches rembg exactly:\n\
             - Resize: Lanczos3 (NOT bilinear)\n\
             - Normalization: max(max_pixel, 1e-6) (NOT 255.0)\n\
             - Postprocessing: min-max only (NOT sigmoid, NOT threshold)"
        );

        println!("rembg reference [{stem}]: {pct:.1}% pixel match (tolerance=\u{b1}{tolerance}, required={required_pct}%) PASS");
    }
}

